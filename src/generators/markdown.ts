// ── ICONS MARKDOWN ────────────────────────────────────────────
function buildIconsMarkdown(state: AppState): string {
  const { icons } = state
  if (!icons.selected.length) return ''

  // Use only local assets and force row breaks so "icons per row" is respected.
  const perRow = getSafePerRow(icons.perRow)
  const align = icons.align === 'left' ? 'left' : 'center'
  const rows: string[][] = []
  for (let i = 0; i < icons.selected.length; i += perRow) {
    rows.push(icons.selected.slice(i, i + perRow))
  }

  const rowsMd = rows.map(row =>
    row.map(id =>
      `<img src="./assets/icons/${id}.svg" width="40" alt="${id}" title="${id}" />`
    ).join(' ')
  ).join('\n<br />\n')

  return `<div align="${align}">\n\n${rowsMd}\n\n</div>`
}

function getSafePerRow(value: number): number {
  return Number.isFinite(value) ? Math.min(20, Math.max(1, value)) : 12
}

// ── SOCIAL BADGES ─────────────────────────────────────────────
function normalizeHex(value: string): string {
  const hex = value.replace('#', '').trim()
  return /^[0-9a-fA-F]{6}$/.test(hex) ? hex : '58a6ff'
}

function buildSocialBadges(state: AppState): string {
  const { social } = state
  const badges: string[] = []

  const SOCIAL_DEFS: Array<{ key: keyof typeof social; label: string; labelColor: string; msgColor: string; icon: string }> = [
    { key: 'linkedin',  label: 'LinkedIn',  labelColor: '0077B5', msgColor: '0077B5', icon: 'linkedin' },
    { key: 'twitter',   label: 'Twitter',   labelColor: '1DA1F2', msgColor: '1DA1F2', icon: 'twitter' },
    { key: 'website',   label: 'Portfolio', labelColor: 'FF5722', msgColor: 'FF5722', icon: 'website' },
    { key: 'email',     label: 'Email',     labelColor: 'D14836', msgColor: 'D14836', icon: 'email' },
    { key: 'discord',   label: 'Discord',   labelColor: '5865F2', msgColor: '5865F2', icon: 'discord' },
    { key: 'youtube',   label: 'YouTube',   labelColor: 'FF0000', msgColor: 'FF0000', icon: 'youtube' },
    { key: 'devto',     label: 'Dev.to',    labelColor: '0A0A0A', msgColor: '0A0A0A', icon: 'devto' },
  ]

  for (const def of SOCIAL_DEFS) {
    const val = social[def.key]
    if (!val) continue
    const svg = generateBadgeSVG({
      label: def.label, message: '',
      labelColor: def.labelColor, messageColor: def.msgColor,
      style: 'for-the-badge',
    })
    // Just use local badge + link
    const url = getSocialUrl(def.key, val)
    badges.push(`<a href="${url}"><img src="${svgToDataURI(svg)}" alt="${def.label}"></a>`)
  }

  return badges.length ? badges.join('\n') : ''
}

function getSocialUrl(key: string, val: string): string {
  switch(key) {
    case 'linkedin': return `https://linkedin.com/in/${val}`
    case 'twitter':  return `https://twitter.com/${val.replace('@','')}`
    case 'website':  return val.startsWith('http') ? val : 'https://' + val
    case 'email':    return `mailto:${val}`
    case 'discord':  return `https://discord.gg/${val}`
    case 'youtube':  return `https://youtube.com/@${val}`
    case 'devto':    return `https://dev.to/${val}`
    default: return '#'
  }
}

// ── PROJECT CARDS ─────────────────────────────────────────────
function buildProjectCard(proj: PinnedProject): string {
  const stars = proj.stars ? `⭐ ${proj.stars}  ` : ''
  const forks = proj.forks ? `🍴 ${proj.forks}  ` : ''
  const lang  = proj.language ? `\`${proj.language}\`` : ''
  const link  = proj.url ? `[${proj.name}](${proj.url})` : proj.name
  return `**${link}** — ${proj.description}\n${lang} ${stars}${forks}\n\n`
}

// ── UTILS ─────────────────────────────────────────────────────
function svgToDataURI(svg: string): string {
  const encoded = encodeURIComponent(svg)
  return `data:image/svg+xml,${encoded}`
}

function svgToImgTag(svg: string, alt: string): string {
  return `<img src="${svgToDataURI(svg)}" alt="${alt}" width="100%">`
}

function getFocusLabel(focus: string, lang: string): string {
  const map: Record<string, {pt:string;en:string}> = {
    fullstack: {pt:'Full Stack Developer',   en:'Full Stack Developer'},
    backend:   {pt:'Backend Developer',      en:'Backend Developer'},
    frontend:  {pt:'Frontend Developer',     en:'Frontend Developer'},
    mobile:    {pt:'Mobile Developer',       en:'Mobile Developer'},
    devops:    {pt:'DevOps / SRE Engineer',  en:'DevOps / SRE Engineer'},
    data:      {pt:'Data Engineer / AI',     en:'Data Engineer / AI'},
    security:  {pt:'Security Engineer',      en:'Security Engineer'},
    gamedev:   {pt:'Game Developer',         en:'Game Developer'},
    student:   {pt:'Estudante de Dev',       en:'Dev Student'},
  }
  const entry = map[focus]
  if (!entry) return focus
  return lang === 'en' ? entry.en : entry.pt
}

// ── EXPORT ────────────────────────────────────────────────────
export function downloadMarkdown(content: string, filename = 'README.md'): void {
  const blob = new Blob([content], { type: 'text/markdown' })
  const url  = URL.createObjectURL(blob)
  const a    = document.createElement('a')
  a.href = url; a.download = filename; a.click()
  URL.revokeObjectURL(url)
}
