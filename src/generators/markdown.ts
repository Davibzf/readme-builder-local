// Base URL for assets when the README is hosted in the user's own repo
// User should set this to their repo's raw URL after downloading
const ASSET_NOTE = `<!-- 
  ⚠️  IMPORTANTE: este README foi gerado 100% localmente.
  Os ícones e SVGs estão em ./assets/ neste repositório.
  Copie a pasta assets/ para o seu repositório username/username.
  Nenhum serviço externo é necessário.
-->`

export function generateMarkdown(state: AppState): string {
  const { lang, profile, typing, icons, social, plugins, about, projects, sectionOrder, statsTheme } = state
  const tr = (key: string) => t(lang, key)
  const user = profile.username || 'seu-username'

  // Typing SVG: always embed as data URI in offline-first mode
  const typingConfig = typing
  const font = getFontById(typing.font)
  const lines = typing.texts.filter(s => s.trim())

  let typingMd = ''
  if (lines.length) {
    // Embed the SVG as a data URI so it works without any hosting
    const svg = generateTypingSVG({ ...typingConfig, texts: lines })
    const encoded = svgToDataURI(svg)
    typingMd = `<img src="${encoded}" alt="Typing SVG" />`
  }

  // Icons markdown: inline SVG data URIs (fully offline)
  const iconsMd = buildIconsMarkdown(state)

  // Social badges: inline SVG data URIs
  const socialMd = buildSocialBadges(state)

  // Build ordered sections
  const sections: string[] = []

  sections.push(ASSET_NOTE)
  sections.push('')

  for (const sec of sectionOrder) {
    if (!sec.enabled) continue
    const chunk = buildSection(sec.id, state, { tr, user, typingMd, iconsMd, socialMd, font })
    if (chunk) sections.push(chunk)
  }

  // Footer
  sections.push(`---\n\n<div align="center">\n  <sub>⚡ ${lang === 'pt' ? 'Gerado com' : 'Generated with'} <a href="https://github.com/Davibzf/Readme-Builder">README Builder</a> — 100% local, sem dependências externas.</sub>\n</div>`)

  return sections.join('\n\n')
}

// ── SECTION BUILDERS ─────────────────────────────────────────

function buildSection(
  id: SectionId,
  state: AppState,
  ctx: { tr: (k:string)=>string; user: string; typingMd: string; iconsMd: string; socialMd: string; font: ReturnType<typeof getFontById> }
): string {
  const { tr, user, typingMd, iconsMd, socialMd } = ctx
  const { profile, plugins, about, projects, lang, statsTheme } = state

  switch(id) {
    case 'header': {
      const waveFields = plugins.wave?.fields ?? {}
      const waveColor = normalizeHex(waveFields.color || '58a6ff')
      const waveHeaderText = waveFields.headerText?.trim() ?? ''
      const waveSvg = plugins['wave']?.enabled
        ? svgToImgTag(generateWaveSVG('header', waveColor, 120, waveHeaderText), 'Wave header')
        : ''

      let md = `<div align="center">\n\n`
      if (waveSvg) md += waveSvg + '\n\n'
      md += `# ${profile.displayName}\n`
      md += `### ${getFocusLabel(profile.focus, lang)}\n\n`
      if (profile.bio) md += `> *${profile.bio}*\n\n`
      if (profile.location) md += `📍 ${profile.location}\n\n`
      if (profile.openToWork) {
        const badge = generateBadgeSVG({ label: 'Open to work', message: '✓', labelColor: '238636', messageColor: '2ea043', style: 'flat-square' })
        md += `<img src="${svgToDataURI(badge)}" alt="Open to work">\n\n`
      }
      if (typingMd) md += typingMd + '\n\n'
      if (socialMd) md += socialMd + '\n\n'
      md += `</div>`
      return md
    }

    case 'about': {
      if (!about.enabled) return ''
      let md = `## ${tr('rm_about')}\n\n`
      for (const p of about.paragraphs) {
        if (p.trim()) md += p.trim() + '\n\n'
      }
      const facts = about.facts.filter(f => f.text.trim())
      if (facts.length) {
        md += facts.map(f => `- ${f.emoji} ${f.text}`).join('\n')
        md += '\n'
      }
      return md
    }

    case 'icons': {
      if (!iconsMd) return ''
      return `## ${tr('rm_stack')}\n\n${iconsMd}`
    }

    case 'stats': {
      const hasStats = ['stats','streak','langs'].some(p => plugins[p as keyof typeof plugins]?.enabled)
      if (!hasStats) return ''

      let md = `## ${tr('rm_stats')}\n\n`
      md += `<!-- GitHub Stats cards generated by README Builder. No external card service required. -->\n`
      md += `<div align="center">\n\n`
      if (plugins['stats']?.enabled)
        md += `<img src="${svgToDataURI(generateGithubStatsCard(state))}" alt="GitHub Stats" />\n`
      if (plugins['streak']?.enabled)
        md += `<img src="${svgToDataURI(generateGithubStreakCard(state))}" alt="GitHub Streak" />\n`
      if (plugins['langs']?.enabled)
        md += `<img src="${svgToDataURI(generateTopLangsCard(state))}" alt="Top Languages" />\n`
      md += `\n</div>`
      return md
    }

    case 'projects': {
      const active = projects.filter(p => p.enabled)
      if (!active.length) return ''
      let md = `## ${tr('rm_projects')}\n\n`
      md += `<div align="center">\n\n`
      // Local project cards using inline SVG badges
      for (const proj of active) {
        md += buildProjectCard(proj)
      }
      md += `\n</div>`
      return md
    }

    case 'snake': {
      if (!plugins['snake']?.enabled) return ''
      return generateSnakeReadmeSection(user, lang)
    }

    case 'plugins': {
      return buildPluginsSection(state, tr, user)
    }

    case 'footer': {
      const waveFields = plugins.wave?.fields ?? {}
      const waveColor = normalizeHex(waveFields.color || '58a6ff')
      const waveFooterText = waveFields.footerText?.trim() ?? ''
      const waveSvg = plugins['wave']?.enabled
        ? '\n\n' + svgToImgTag(generateWaveSVG('footer', waveColor, 80, waveFooterText), 'Wave footer')
        : ''
      return `<div align="center">\n  <a href="https://github.com/${user}">github.com/${user}</a>${waveSvg}\n</div>`
    }

    default: return ''
  }
}

